"""Zip bundle: template, values (.env or values.yaml), runner script and a short README."""

from __future__ import annotations

import io
import zipfile

from templatize.ansible import RoleResult
from templatize.build import BuildResult
from templatize.emitters import get_emitter
from templatize.helm import ChartResult

_FIXED_TIME = (2020, 1, 1, 0, 0, 0)  # deterministic archives

README = """\
# Generated template

Files:

- `{template}`: the template ({engine})
- `{values_file}`: the extracted values ({count})
- {runners}

Render it (needs [uv](https://docs.astral.sh/uv/), which installs the dependencies):

    {command}

Or with pip:

    pip install jinja2 {loader_pip}
    python render.py -o output.txt

Edit `{values_file}` to change values{lists}. Round-trip check when generated: {verdict}.
"""


def _count(result: BuildResult) -> str:
    n, k = len(result.ir.variables), len(result.ir.loops)
    out = f"{n} variable{'' if n == 1 else 's'}"
    return out + (f", {k} loop{'' if k == 1 else 's'}" if k else "")


def bundle_readme(result: BuildResult) -> str:
    emitter = get_emitter(result.engine)
    return README.format(
        template=result.template.path,
        engine=result.engine,
        values_file=result.env.path,
        count=_count(result),
        loader_pip="pyyaml" if result.ir.loops else "python-dotenv",
        lists=(
            ": the lists are loops, so adding an item adds a block to the output"
            if result.ir.loops
            else ""
        ),
        runners=", ".join(
            f"`{f.path}`: renders the template with the values" for f in result.runner
        )
        or "no runner script",
        command=emitter.run_command(),
        verdict="PASS" if result.roundtrip.ok else "FAIL",
    )


def make_zip(result: BuildResult) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for f in [*result.files]:
            info = zipfile.ZipInfo(f.path, date_time=_FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o755 if f.path.endswith(".py") else 0o644) << 16
            zf.writestr(info, f.content.encode("utf-8", "surrogatepass"))
        info = zipfile.ZipInfo("README.md", date_time=_FIXED_TIME)
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        zf.writestr(info, bundle_readme(result))
    return buf.getvalue()


CHART_README = """\
# {name}

A Helm chart generated by templatize from {count} Kubernetes resource{plural}.

    helm template {name} .            # render locally
    helm install {name} . -n <namespace>
{overlays}
Round-trip check when generated: {verdict}.
"""


def chart_readme(result: ChartResult) -> str:
    overlays = [f.path for f in result.files if f.path.startswith("values-")]
    lines = "".join(f"    helm template {result.chart_name} . -f {o}\n" for o in overlays)
    return CHART_README.format(
        name=result.chart_name,
        count=len(result.templates),
        plural="" if len(result.templates) == 1 else "s",
        overlays=("\nWith the values of an example document:\n\n" + lines) if lines else "",
        verdict="PASS" if result.ok else "FAIL",
    )


def make_chart_zip(result: ChartResult) -> bytes:
    """``<chart>/...`` so that unzipping yields a chart directory."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        files = [*result.files]
        if not any(f.path == "README.md" for f in files):
            files.append(type(files[0])(path="README.md", content=chart_readme(result)))
        for f in files:
            info = zipfile.ZipInfo(f"{result.chart_name}/{f.path}", date_time=_FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, f.content.encode("utf-8", "surrogatepass"))
    return buf.getvalue()


def make_role_zip(result: RoleResult) -> bytes:
    """``<role>/...`` plus ``playbook.yml``: unzip into a directory and run the playbook."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for f in result.files:
            info = zipfile.ZipInfo(f.path, date_time=_FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, f.content.encode("utf-8", "surrogatepass"))
    return buf.getvalue()
